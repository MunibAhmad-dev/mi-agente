// ============================================================================
// Auto-Documentation Generator
// ============================================================================
// Generates README, workflow explanation, dependencies, models,
// configuration, reproduction instructions from real project state.
// ============================================================================

import type { CaioDatabase, ProjectId } from "../core/types/index.js";

export class AutoDocs {
  constructor(private db: CaioDatabase) {}

  /**
   * Generate a README for a project.
   */
  generateREADME(projectId: ProjectId): string {
    const project = this.db.get<{
      id: string; name: string; description: string | null; config: string; tags: string;
    }>("SELECT * FROM projects WHERE id = ?", projectId);

    if (!project) return "# Project Not Found";

    const config = JSON.parse(project.config);
    const tags = JSON.parse(project.tags);

    // Get workflows
    const workflows = this.db.all<{ name: string; version: string; nodes: string; metadata: string }>(
      "SELECT name, version, nodes, metadata FROM workflows WHERE project_id = ?", projectId
    );

    // Get experiments
    const experiments = this.db.get<{ count: number; best_score: number | null }>(
      "SELECT COUNT(*) as count, MAX(quality_score) as best_score FROM experiments WHERE project_id = ? AND status = 'completed'",
      projectId
    );

    let md = `# ${project.name}\n\n`;
    if (project.description) md += `${project.description}\n\n`;

    // Tags
    if (tags.length > 0) {
      md += `**Tags:** ${tags.join(", ")}\n\n`;
    }

    // Configuration
    md += `## Configuration\n\n`;
    md += `- **Mode:** ${config.mode}\n`;
    md += `- **Autonomy:** ${config.autonomyLevel}\n`;
    md += `- **Network:** ${config.networkPolicy}\n\n`;

    // Workflows
    if (workflows.length > 0) {
      md += `## Workflows (${workflows.length})\n\n`;
      for (const wf of workflows) {
        const nodes = JSON.parse(wf.nodes);
        const meta = JSON.parse(wf.metadata);
        md += `### ${wf.name} v${wf.version}\n\n`;
        md += `- Nodes: ${nodes.length}\n`;
        if (meta.estimatedVramMb) md += `- Est. VRAM: ${meta.estimatedVramMb}MB\n`;
        if (meta.requiredModels?.length > 0) {
          md += `- Required models: ${meta.requiredModels.map((m: any) => m.name).join(", ")}\n`;
        }
        md += `\n`;
      }
    }

    // Experiments
    if (experiments && experiments.count > 0) {
      md += `## Experiments\n\n`;
      md += `- Total: ${experiments.count}\n`;
      if (experiments.best_score) md += `- Best score: ${experiments.best_score}\n`;
      md += `\n`;
    }

    // Reproduction
    md += `## Reproduction\n\n`;
    md += "1. Install CAIO: `npm install`\n";
    md += "2. Start server: `npm start`\n";
    if (workflows.length > 0) {
      md += `3. Import workflow via API or UI\n`;
    }
    md += `\n---\n*Auto-generated by Creative AI Orchestrator*\n`;

    return md;
  }
}
