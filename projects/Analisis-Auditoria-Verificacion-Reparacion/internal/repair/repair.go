// Package repair implements the Repair Engine (spec: DIAGNOSIS → REPAIR).
// MVP repairs are deliberately conservative: annotations, report-only fixes,
// and test stubs. Code rewrites require RepairCodeFixes=true AND explicit
// user configuration, because repairs must never mask real defects.
package repair

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"verificationengine/internal/core"
)

// Config controls what the repair engine may do.
type Config struct {
	RepairCodeFixes bool   `json:"repair_code_fixes"` // allow code edits (default false)
	NotesDir        string `json:"notes_dir"`         // where repair notes go (default reports/)
}

// Repair is one applied (or proposed) repair.
type Repair struct {
	Rule        string `json:"rule"`
	Target      string `json:"target"`
	Location    string `json:"location,omitempty"`
	Action      string `json:"action"` // annotated|stub_test|report|skipped_needs_code_fix
	Detail      string `json:"detail"`
	Evidence    string `json:"evidence,omitempty"`
	AppliedCode bool   `json:"applied_code"`
}

// Engine applies safe repairs for known findings.
type Engine struct {
	cfg   Config
	runID string
}

// NewEngine builds a repair engine.
func NewEngine(cfg Config, runID string) *Engine {
	if cfg.NotesDir == "" {
		cfg.NotesDir = "reports"
	}
	return &Engine{cfg: cfg, runID: runID}
}

// RepairFindings walks findings and applies safe repairs. Non-actionable
// rule classes are aggregated into one queue line per rule (the full list
// lives in evidence.jsonl), keeping the repair queue actionable.
func (e *Engine) RepairFindings(root string, findings []core.Evidence) []Repair {
	var out []Repair
	aggregate := map[string]int{}
	aggSample := map[string]string{}
	for _, f := range findings {
		switch f.Rule {
		case "R0100": // placeholder
			r := Repair{Rule: f.Rule, Target: f.Target, Location: f.Location}
			if e.cfg.RepairCodeFixes {
				r.Action = "skipped_needs_code_fix"
				r.Detail = "placeholder removal requires human/agent code fix; engine never auto-implements features (EVIDENCE > CLAIM)"
				r.AppliedCode = false
			} else {
				r.Action = "annotated"
				r.Detail = "placeholder finding recorded for repair queue"
			}
			out = append(out, r)
		case "R0600": // weak test
			out = append(out, e.stubTest(root, f))
		case "R0200": // dead code
			out = append(out, Repair{Rule: f.Rule, Target: f.Target, Location: f.Location,
				Action: "report", Detail: "dead code candidate requires human decision (delete or wire)"})
		default:
			aggregate[f.Rule]++
			if aggSample[f.Rule] == "" {
				aggSample[f.Rule] = f.Location
			}
		}
	}
	// One queue line per aggregated rule (details in evidence.jsonl).
	rules := make([]string, 0, len(aggregate))
	for rule := range aggregate {
		rules = append(rules, rule)
	}
	sort.Strings(rules)
	for _, rule := range rules {
		out = append(out, Repair{Rule: rule, Target: "rule:" + rule, Location: aggSample[rule],
			Action: "report", Detail: fmt.Sprintf("%d finding(s) recorded; no automatic repair (details in evidence.jsonl)", aggregate[rule])})
	}
	return out
}

// stubTest writes a failing-first test stub for an untested/dead function.
func (e *Engine) stubTest(root string, f core.Evidence) Repair {
	r := Repair{Rule: f.Rule, Target: f.Target, Action: "stub_test"}
	testDir := filepath.Join(root, "internal", "repair", "teststubs")
	if err := os.MkdirAll(testDir, 0o755); err != nil {
		r.Detail = "failed to create stub dir: " + err.Error()
		return r
	}
	name := "TestStub_" + sanitize(f.Target)
	path := filepath.Join(testDir, "stub_test.go")
	// Only create once per target.
	marker := "// RepairStub:" + f.Target
	if data, err := os.ReadFile(path); err == nil && strings.Contains(string(data), marker) {
		r.Detail = "stub already exists for " + f.Target
		return r
	}
	content := fmt.Sprintf("// Code generated by repair engine. DO NOT EDIT.\npackage teststubs\n\nimport \"testing\"\n\n%s\nfunc %s(t *testing.T) {\n\tt.Skip(\"repair engine stub: implement test for %s (EVIDENCE > CLAIM)\")\n}\n",
		marker, name, f.Target)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		r.Detail = "failed to write stub: " + err.Error()
		return r
	}
	r.Detail = "wrote test stub for " + f.Target
	r.AppliedCode = true
	return r
}

func sanitize(s string) string {
	var b strings.Builder
	for _, c := range s {
		switch {
		case c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9':
			b.WriteRune(c)
		default:
			b.WriteRune('_')
		}
	}
	return b.String()
}
