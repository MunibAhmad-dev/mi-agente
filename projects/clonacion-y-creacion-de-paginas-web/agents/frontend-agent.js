import { AgentBase } from '../core/agent-base.js';
import { ensureDir, projectDir, writeJSON, readJSON } from '../core/utils.js';
import { join } from 'node:path';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';

export class FrontendAgent extends AgentBase {
  constructor(config = {}) {
    super({
      ...config,
      type: 'frontend',
      name: 'Frontend Agent',
      capabilities: ['code-generation', 'react-generation', 'html-generation', 'css-generation'],
    });
  }

  async perform(task, context) {
    const { action } = task;
    this.log.info(`Frontend action: ${action}`);

    switch (action) {
      case 'generate': return this.generate(task, context);
      default: throw new Error(`Unknown frontend action: ${action}`);
    }
  }

  async generate(task, context) {
    const { framework = 'html', designDNA, domData, cssData } = task;
    const projectId = context?.projectId;
    const projectPath = projectDir(projectId);
    const outDir = ensureDir(`${projectPath}/output`);

    this.log.info(`Generating ${framework} code from DOM/CSS data...`);

    // Build comprehensive CSS from all available data
    const css = this.buildCSS(designDNA, cssData);

    // Build real HTML from DOM structure
    const html = this.buildHTML(designDNA, domData, cssData, css);

    const htmlPath = join(outDir, 'reconstruction.html');
    writeFileSync(htmlPath, html, 'utf-8');
    this.log.info(`HTML generated: ${htmlPath}`);

    return {
      evidence: [
        { type: 'file', description: 'Generated HTML/CSS reconstruction', path: htmlPath },
      ],
    };
  }

  // ─── Build CSS from all sources ──────────────────────────────────────────

  buildCSS(dna, cssData) {
    const lines = [];
    lines.push('/* Generated by Universal Web Reconstruction Engine */');
    lines.push('/* Reset */');
    lines.push('*, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }');
    lines.push('');

    // Extract colors from computed styles
    const colors = this.extractColorsFromCSS(cssData);
    const fonts = this.extractFontsFromCSS(cssData);
    const spacings = this.extractSpacingsFromCSS(cssData);

    // CSS Variables from extracted data
    lines.push(':root {');
    if (colors.primary) lines.push(`  --color-primary: ${colors.primary};`);
    if (colors.secondary) lines.push(`  --color-secondary: ${colors.secondary};`);
    if (colors.accent) lines.push(`  --color-accent: ${colors.accent};`);
    if (colors.background) lines.push(`  --color-bg: ${colors.background};`);
    if (colors.surface) lines.push(`  --color-surface: ${colors.surface};`);
    if (colors.text) lines.push(`  --color-text: ${colors.text};`);
    if (colors.textSecondary) lines.push(`  --color-text-secondary: ${colors.textSecondary};`);
    if (colors.border) lines.push(`  --color-border: ${colors.border};`);
    if (fonts.primary) lines.push(`  --font-primary: ${fonts.primary};`);
    if (fonts.secondary) lines.push(`  --font-secondary: ${fonts.secondary};`);
    lines.push('}');
    lines.push('');

    // Generate component styles from CSS data
    if (cssData?.length) {
      lines.push('/* Component styles from extracted CSS */');
      for (const item of cssData.slice(0, 100)) {
        const selector = item.selector || item.tag;
        if (!selector) continue;

        const styles = item.styles || {};
        const cssProps = [];

        // Layout
        if (styles.display && styles.display !== 'inline') cssProps.push(`display: ${styles.display}`);
        if (styles.position && styles.position !== 'static') cssProps.push(`position: ${styles.position}`);

        // Box model
        if (styles.width && styles.width !== 'auto') cssProps.push(`width: ${styles.width}`);
        if (styles.height && styles.height !== 'auto') cssProps.push(`height: ${styles.height}`);
        if (styles.maxWidth && styles.maxWidth !== 'none') cssProps.push(`max-width: ${styles.maxWidth}`);
        if (styles.padding && styles.padding !== '0px') cssProps.push(`padding: ${styles.padding}`);
        if (styles.margin && styles.margin !== '0px') cssProps.push(`margin: ${styles.margin}`);
        if (styles.gap && styles.gap !== 'normal') cssProps.push(`gap: ${styles.gap}`);

        // Colors
        if (styles.backgroundColor && styles.backgroundColor !== 'rgba(0, 0, 0, 0)' && styles.backgroundColor !== 'transparent') {
          cssProps.push(`background-color: ${styles.backgroundColor}`);
        }
        if (styles.color && styles.color !== 'rgb(0, 0, 0)') cssProps.push(`color: ${styles.color}`);

        // Typography
        if (styles.fontSize) cssProps.push(`font-size: ${styles.fontSize}`);
        if (styles.fontFamily) cssProps.push(`font-family: ${styles.fontFamily}`);
        if (styles.fontWeight && styles.fontWeight !== 'normal') cssProps.push(`font-weight: ${styles.fontWeight}`);
        if (styles.lineHeight && styles.lineHeight !== 'normal') cssProps.push(`line-height: ${styles.lineHeight}`);
        if (styles.textAlign && styles.textAlign !== 'start') cssProps.push(`text-align: ${styles.textAlign}`);
        if (styles.letterSpacing && styles.letterSpacing !== 'normal') cssProps.push(`letter-spacing: ${styles.letterSpacing}`);

        // Borders
        if (styles.borderRadius && styles.borderRadius !== '0px') cssProps.push(`border-radius: ${styles.borderRadius}`);
        if (styles.boxShadow && styles.boxShadow !== 'none') cssProps.push(`box-shadow: ${styles.boxShadow}`);

        // Other
        if (styles.opacity && styles.opacity !== '1') cssProps.push(`opacity: ${styles.opacity}`);
        if (styles.overflow && styles.overflow !== 'visible') cssProps.push(`overflow: ${styles.overflow}`);
        if (styles.zIndex && styles.zIndex !== 'auto' && styles.zIndex !== '0') cssProps.push(`z-index: ${styles.zIndex}`);
        if (styles.transition && styles.transition !== 'all 0s ease 0s') cssProps.push(`transition: ${styles.transition}`);
        if (styles.transform && styles.transform !== 'none') cssProps.push(`transform: ${styles.transform}`);

        if (cssProps.length > 0) {
          const cleanSelector = this.cleanSelector(selector);
          if (!cleanSelector) continue;  // Skip non-visual elements
          lines.push(`${cleanSelector} {`);
          for (const prop of cssProps) {
            lines.push(`  ${prop};`);
          }
          lines.push('}');
          lines.push('');
        }
      }
    }

    // Add global styles
    lines.push('/* Global styles */');
    lines.push('body {');
    lines.push(`  font-family: ${fonts.primary || 'system-ui, -apple-system, sans-serif'};`);
    lines.push(`  background-color: ${colors.background || '#ffffff'};`);
    lines.push(`  color: ${colors.text || '#1a1a1a'};`);
    lines.push('  line-height: 1.5;');
    lines.push('  -webkit-font-smoothing: antialiased;');
    lines.push('}');
    lines.push('');
    lines.push('a { color: inherit; text-decoration: none; }');
    lines.push('img { max-width: 100%; display: block; }');
    lines.push('button { cursor: pointer; border: none; background: none; font: inherit; }');
    lines.push('');
    lines.push('@media (max-width: 768px) {');
    lines.push('  .container { padding: 16px; }');
    lines.push('  .sidebar { display: none; }');
    lines.push('}');

    return lines.join('\n');
  }

  // ─── Build HTML from DOM structure ───────────────────────────────────────

  buildHTML(dna, domData, cssData, css) {
    const body = domData ? this.domToHTML(domData) : this.generateFromDesignDNA(dna);

    // Extract body styles from DOM for the body tag
    let bodyStyle = '';
    if (domData?.styles) {
      const s = domData.styles;
      const parts = [];
      if (s.backgroundColor && s.backgroundColor !== 'rgba(0, 0, 0, 0)') parts.push(`background-color:${s.backgroundColor}`);
      if (s.color && s.color !== 'rgb(0, 0, 0)') parts.push(`color:${s.color}`);
      if (s.fontFamily) parts.push(`font-family:${s.fontFamily}`);
      if (s.fontSize) parts.push(`font-size:${s.fontSize}`);
      if (s.display) parts.push(`display:${s.display}`);
      if (parts.length) bodyStyle = ` style="${parts.join(';')}"`;
    }

    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${dna?.screens?.[0]?.name || 'Reconstruction'}</title>
  <style>
${css}
  </style>
</head>
<body${bodyStyle}>
${body}
</body>
</html>`;
  }

  // ─── DOM to HTML conversion ──────────────────────────────────────────────

  domToHTML(node, depth = 0) {
    if (!node || depth > 15) return '';
    if (['script', 'style', 'noscript', 'svg'].includes(node.tag)) return '';

    // Skip body/html/head tags - render only children
    if (['body', 'html', 'head'].includes(node.tag) && depth === 0) {
      return (node.children || []).map(c => this.domToHTML(c, 0)).join('\n');
    }

    const tag = node.tag || 'div';
    const attrs = [];

    if (node.id) attrs.push(`id="${node.id}"`);
    if (node.classes) attrs.push(`class="${node.classes}"`);
    if (node.role) attrs.push(`role="${node.role}"`);

    // Add inline styles for critical layout properties
    const inlineStyles = [];
    if (node.rect) {
      if (node.rect.width > 0 && node.rect.width < 2000) {
        inlineStyles.push(`width:${node.rect.width}px`);
      }
    }
    if (node.styles) {
      if (node.styles.display) inlineStyles.push(`display:${node.styles.display}`);
      if (node.styles.position && node.styles.position !== 'static') {
        inlineStyles.push(`position:${node.styles.position}`);
      }
      if (node.styles.backgroundColor && node.styles.backgroundColor !== 'rgba(0, 0, 0, 0)' && node.styles.backgroundColor !== 'transparent') {
        inlineStyles.push(`background-color:${node.styles.backgroundColor}`);
      }
      if (node.styles.color && node.styles.color !== 'rgb(0, 0, 0)') {
        inlineStyles.push(`color:${node.styles.color}`);
      }
      if (node.styles.fontSize) inlineStyles.push(`font-size:${node.styles.fontSize}`);
      if (node.styles.fontWeight && node.styles.fontWeight !== 'normal') {
        inlineStyles.push(`font-weight:${node.styles.fontWeight}`);
      }
      if (node.styles.padding && node.styles.padding !== '0px') {
        inlineStyles.push(`padding:${node.styles.padding}`);
      }
      if (node.styles.margin && node.styles.margin !== '0px') {
        inlineStyles.push(`margin:${node.styles.margin}`);
      }
      if (node.styles.borderRadius && node.styles.borderRadius !== '0px') {
        inlineStyles.push(`border-radius:${node.styles.borderRadius}`);
      }
      if (node.styles.boxShadow && node.styles.boxShadow !== 'none') {
        inlineStyles.push(`box-shadow:${node.styles.boxShadow}`);
      }
      if (node.styles.gap && node.styles.gap !== 'normal') {
        inlineStyles.push(`gap:${node.styles.gap}`);
      }
      if (node.styles.flexDirection) inlineStyles.push(`flex-direction:${node.styles.flexDirection}`);
      if (node.styles.justifyContent) inlineStyles.push(`justify-content:${node.styles.justifyContent}`);
      if (node.styles.alignItems) inlineStyles.push(`align-items:${node.styles.alignItems}`);
      if (node.styles.textAlign && node.styles.textAlign !== 'start') {
        inlineStyles.push(`text-align:${node.styles.textAlign}`);
      }
      if (node.styles.overflow && node.styles.overflow !== 'visible') {
        inlineStyles.push(`overflow:${node.styles.overflow}`);
      }
      if (node.styles.border && node.styles.border !== 'none' && node.styles.border !== '0px none rgb(0, 0, 0)') {
        inlineStyles.push(`border:${node.styles.border}`);
      }
    }

    if (inlineStyles.length > 0) {
      attrs.push(`style="${inlineStyles.join(';')}"`);
    }

    const attrStr = attrs.length > 0 ? ' ' + attrs.join(' ') : '';
    const text = node.text ? this.escapeHTML(node.text) : '';
    const children = (node.children || []).map(c => this.domToHTML(c, depth + 1)).join('\n');

    // Self-closing tags
    if (['img', 'br', 'hr', 'input'].includes(tag)) {
      return `${'  '.repeat(depth)}<${tag}${attrStr} />`;
    }

    if (text && !children) {
      return `${'  '.repeat(depth)}<${tag}${attrStr}>${text}</${tag}>`;
    }

    return `${'  '.repeat(depth)}<${tag}${attrStr}>\n${children}\n${'  '.repeat(depth)}</${tag}>`;
  }

  // ─── Generate from Design DNA (fallback) ─────────────────────────────────

  generateFromDesignDNA(dna) {
    if (!dna) return '<div class="container"><h1>Reconstruction</h1></div>';

    const components = dna.components || [];
    if (components.length === 0) {
      return '<div class="container"><h1>Reconstruction Output</h1><p>Generated by Universal Web Reconstruction Engine</p></div>';
    }

    return components.map(c => {
      const tag = c.tag || 'div';
      const id = c.id ? ` id="${c.id}"` : '';
      const text = c.text ? `<span>${c.text}</span>` : '';
      const children = (c.children || []).map(child => {
        const ctag = child.tag || 'div';
        const cid = child.id ? ` id="${child.id}"` : '';
        return `      <${ctag}${cid}>${child.text || ''}</${ctag}>`;
      }).join('\n');
      return `  <${tag}${id}>\n${children}\n  </${tag}>`;
    }).join('\n');
  }

  // ─── Color Extraction ────────────────────────────────────────────────────

  extractColorsFromCSS(cssData) {
    const colors = {
      primary: null, secondary: null, accent: null,
      background: null, surface: null, text: null,
      textSecondary: null, border: null,
    };

    if (!cssData?.length) return colors;

    const colorMap = new Map();
    for (const item of cssData) {
      const s = item.styles || {};
      for (const prop of ['backgroundColor', 'color']) {
        const val = s[prop];
        if (val && val !== 'rgba(0, 0, 0, 0)' && val !== 'transparent' && val !== 'rgb(0, 0, 0)') {
          colorMap.set(val, (colorMap.get(val) || 0) + 1);
        }
      }
    }

    // Sort by frequency
    const sorted = [...colorMap.entries()].sort((a, b) => b[1] - a[1]);

    // Assign colors based on frequency patterns
    let bgFound = false, textFound = false;
    for (const [color, count] of sorted) {
      const isLight = this.isLightColor(color);
      const isDark = this.isDarkColor(color);

      if (isLight && !bgFound && count > 5) {
        colors.background = color;
        bgFound = true;
      } else if (isDark && !textFound && count > 3) {
        colors.text = color;
        textFound = true;
      } else if (!colors.accent && count > 2) {
        colors.accent = color;
      } else if (!colors.secondary && count > 1) {
        colors.secondary = color;
      }
    }

    // Defaults
    colors.background = colors.background || '#ffffff';
    colors.text = colors.text || '#1a1a1a';
    colors.border = colors.border || '#e5e7eb';

    return colors;
  }

  extractFontsFromCSS(cssData) {
    const fonts = { primary: null, secondary: null };
    if (!cssData?.length) return fonts;

    const fontMap = new Map();
    for (const item of cssData) {
      const ff = item.styles?.fontFamily;
      if (ff) {
        const primary = ff.split(',')[0].trim().replace(/"/g, '');
        fontMap.set(primary, (fontMap.get(primary) || 0) + 1);
      }
    }

    const sorted = [...fontMap.entries()].sort((a, b) => b[1] - a[1]);
    if (sorted.length > 0) fonts.primary = sorted[0][0];
    if (sorted.length > 1) fonts.secondary = sorted[1][0];

    return fonts;
  }

  extractSpacingsFromCSS(cssData) {
    return { gaps: [], paddings: [], margins: [] };
  }

  // ─── Helpers ─────────────────────────────────────────────────────────────

  cleanSelector(selector) {
    // Skip non-visual elements entirely
    const skipTags = ['html', 'head', 'title', 'meta', 'link', 'style', 'script', 'noscript', 'svg'];
    const tagMatch = selector.match(/^([a-zA-Z]+)/);
    if (tagMatch && skipTags.includes(tagMatch[1].toLowerCase())) return null;

    // Clean up selector: remove trailing dots from element-only selectors
    let clean = selector
      .replace(/\s+/g, ' ')
      .replace(/\.(\s|$)/g, ' ')  // Remove trailing dots
      .replace(/\.+/g, '.')         // Collapse multiple dots
      .trim();

    // If only a tag name remains (no class/id), skip it
    if (/^[a-zA-Z]+$/.test(clean)) return null;

    return clean.substring(0, 100);
  }

  escapeHTML(str) {
    return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  isLightColor(color) {
    if (!color) return false;
    const match = color.match(/rgb\((\d+),\s*(\d+),\s*(\d+)\)/);
    if (!match) return false;
    const [, r, g, b] = match.map(Number);
    return (r * 299 + g * 587 + b * 114) / 1000 > 200;
  }

  isDarkColor(color) {
    if (!color) return false;
    const match = color.match(/rgb\((\d+),\s*(\d+),\s*(\d+)\)/);
    if (!match) return false;
    const [, r, g, b] = match.map(Number);
    return (r * 299 + g * 587 + b * 114) / 1000 < 80;
  }
}
