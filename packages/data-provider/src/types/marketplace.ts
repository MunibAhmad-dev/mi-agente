/**
 * Marketplace Types
 * =================
 * Tipos para el sistema de Marketplace de skills y plugins
 */

import type { DiscoverySource, PluginType } from './discovery';

export type MarketplaceSource = DiscoverySource;

export interface SkillRating {
  id: string;
  score: number; // 1-5
  comment: string;
  author: string;
  createdAt: string;
}

export interface SkillReview {
  id: string;
  skillId: string;
  rating: SkillRating;
  helpful: number;
  notHelpful: number;
}

export interface MarketplaceSkill {
  id: string;
  name: string;
  description: string;
  longDescription?: string;
  source: MarketplaceSource;
  type: PluginType;
  url: string;
  stars?: number;
  downloads?: number;
  author?: string;
  authorUrl?: string;
  tags: string[];
  categories: string[];
  installationCommands: {
    agent: string;
    command: string;
    notes?: string;
  }[];
  compatibleAgents: string[];
  requirements?: string[];
  version?: string;
  lastUpdated?: string;
  verified: boolean;
  featured: boolean;
  rating?: number;
  reviewCount?: number;
  metadata?: Record<string, unknown>;
}

export interface MarketplaceCategory {
  id: string;
  name: string;
  description: string;
  icon: string;
  color: string;
  skillCount: number;
  featuredSkills: string[]; // IDs
}

export interface MarketplaceSearchFilters {
  sources?: MarketplaceSource[];
  types?: PluginType[];
  categories?: string[];
  agents?: string[];
  minRating?: number;
  verifiedOnly?: boolean;
  featuredOnly?: boolean;
  sortBy?: 'rating' | 'downloads' | 'newest' | 'name';
}

export interface MarketplaceStats {
  totalSkills: number;
  totalCategories: number;
  totalDownloads: number;
  averageRating: number;
  topContributors: { author: string; count: number }[];
}

